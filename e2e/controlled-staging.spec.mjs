import {test,expect} from '@playwright/test'
import {readFileSync} from 'node:fs'

const enabled=process.env.ASSET_OS_FULLSTACK_STAGE==='1'

const tenant=enabled?JSON.parse(readFileSync('/tmp/asset-os-stage-tenant.json','utf8')).tenantId:''
test('B2.1 browser → test OIDC PKCE → real Fastify → PostgreSQL lifecycle/ownership/disposition',async({page,request})=>{
 test.skip(!enabled,'Only run against ephemeral PostgreSQL + signed test issuer in dedicated CI stage')
 test.setTimeout(120000)
 let bearer=''
 page.on('request',r=>{
  if(r.url().includes('127.0.0.1:3001/v1/assets')){
   const value=r.headers()['authorization']
   if(value)bearer=value
  }
 })
 await page.goto('./#/server-registry')
 await expect(page.getByRole('button',{name:/Sign in securely/})).toBeVisible()
 await page.getByRole('button',{name:/Sign in securely/}).click()
 await expect(page.getByRole('textbox',{name:'Tenant UUID'})).toBeVisible()
 expect(page.url()).not.toContain('?code=')
 await page.getByRole('textbox',{name:'Tenant UUID'}).fill(tenant)
 await page.getByRole('button',{name:'Verify membership'}).click()
 await expect(page.locator('.server-status')).toContainText('Verified tenant')
 await expect(page.getByRole('heading',{name:'Server Asset Registry'})).toBeVisible()
 // A fresh server-created asset; never seed from browser-local demonstration state.
 await page.getByRole('button',{name:'Register asset'}).click()
 await page.getByLabel('Asset name').fill('B2.1 CI browser-to-Postgres vehicle')
 await page.getByLabel('Asset name').press('Tab')
 await page.getByRole('button',{name:'Register asset'}).click()
 await expect(page.getByRole('heading',{name:'B2.1 CI browser-to-Postgres vehicle'})).toBeVisible()
 const match=page.url().match(/server-registry\/asset\/([0-9a-f-]{36})/i)
 expect(match).toBeTruthy()
 const id=match[1]
 await page.getByRole('button',{name:/Lifecycle, acquisition & ownership/}).click()
 await expect(page.getByRole('heading',{name:'Lifecycle authority'})).toBeVisible()
 await expect(page.locator('.b21-workflow > .b21-summary')).toContainText('Planned')
 await page.getByLabel('Reason for transition').fill('Controlled CI acquisition review')
 await page.getByRole('button',{name:'Begin acquisition'}).click()
 await expect(page.locator('.b21-workflow > .b21-summary')).toContainText('Acquisition Pending')
 await page.locator('.b21-tabs').getByRole('button',{name:'Acquisition',exact:true}).click()
 await page.getByLabel('Cost purchase').fill('1250.00')
 await page.getByLabel('Cost taxes').fill('50.25')
 await page.getByRole('button',{name:/Record acquisition & cost basis/}).click()
 await expect(page.locator('.b21-workflow > .b21-summary')).toContainText('Acquired')
 await expect(page.locator('.b21-workflow > .b21-summary')).toContainText('1300.25 KES')
 await page.locator('.b21-tabs').getByRole('button',{name:'Ownership',exact:true}).click()
 await page.getByLabel('Party reference').fill('ci-owner-a')
 await page.getByLabel('Party display label').fill('Recorded CI Owner A')
 await page.getByLabel('Ownership percentage').fill('75.00')
 await page.getByRole('button',{name:'Record ownership claim'}).click()
 await expect(page.locator('.b21-table')).toContainText('Recorded CI Owner A')
 await expect(page.locator('.b21-ownership-totals')).toContainText('75.00%')
 await page.getByLabel('Source ownership interest').selectOption({index:1})
 await page.getByLabel('Recipient party reference').fill('ci-owner-b')
 await page.getByLabel('Recipient display label').fill('Recorded CI Owner B')
 await page.getByLabel('Share to transfer').fill('25.00')
 await page.getByRole('button',{name:'Record transfer'}).click()
 await expect(page.locator('.b21-table')).toContainText('Recorded CI Owner B')
 await expect(page.locator('.b21-ownership-totals')).toContainText('75.00%')
 await page.locator('.b21-tabs').getByRole('button',{name:'Overview',exact:true}).click()
 await page.getByLabel('Reason for transition').fill('CI verification of asset availability')
 await page.getByRole('button',{name:'Activate asset'}).click()
 await expect(page.locator('.b21-workflow > .b21-summary')).toContainText('Active')
 await page.locator('.b21-tabs').getByRole('button',{name:'Disposition',exact:true}).click()
 await page.getByLabel('Disposition proceeds').fill('1500.00')
 await page.getByLabel('Disposition costs').fill('25.00')
 await page.getByLabel('Reason and evidence context').fill('CI recorded disposition')
 await page.getByLabel('Confirmation (type DISPOSE)').fill('DISPOSE')
 await page.getByRole('button',{name:'Confirm recorded disposition'}).click()
 await expect(page.locator('.b21-workflow > .b21-summary')).toContainText('Disposed')
 await expect(page.locator('.b21-workflow > .b21-summary')).toContainText('174.75 KES')
 await page.locator('.b21-tabs').getByRole('button',{name:'Overview',exact:true}).click()
 await page.getByLabel('Reason for transition').fill('Preserve the historic CI asset')
 await page.getByRole('button',{name:'Archive disposed asset'}).click()
 await expect(page.locator('.b21-workflow > .b21-summary')).toContainText('Archived')
 await page.locator('.b21-tabs').getByRole('button',{name:'History',exact:true}).click()
 await expect(page.locator('.b21-history')).toContainText('Ownership Transfer')
 expect(bearer).toMatch(/^Bearer [^.]+\.[^.]+\.[^.]+$/)
 // The snapshot is retrieved directly from the live API; no Playwright mock route exists.
 const response=await request.get('http://127.0.0.1:3001/v1/assets/'+id+'/lifecycle',{
  headers:{Authorization:bearer,'X-Tenant-Id':tenant}})
 expect(response.status()).toBe(200)
 const persisted=await response.json()
 expect(persisted.asset.lifecycle).toBe('ARCHIVED')
 expect(persisted.acquisition.costBasis).toBe('1300.25')
 expect(persisted.disposition.estimatedGain).toBe('174.75')
 const active=persisted.ownershipInterests.filter(i=>i.effectiveTo===null&&i.dimension==='ECONOMIC')
 expect(active.map(i=>i.percentage).sort()).toEqual(['25.00','50.00'])
 expect(persisted.ownershipChanges.some(x=>x.kind==='TRANSFER')).toBeTruthy()
 const crossTenant=await request.get('http://127.0.0.1:3001/v1/assets/'+id+'/lifecycle',{
  headers:{Authorization:bearer,'X-Tenant-Id':'eeeeeeee-eeee-4eee-8eee-eeeeeeeeeeee'}})
 expect(crossTenant.status()).toBe(403)
 const browserStorage=await page.evaluate(()=>JSON.stringify([...Object.entries(localStorage),...Object.entries(sessionStorage)]))
 expect(browserStorage).not.toContain(bearer.slice(7))
 await page.getByRole('button',{name:'Sign out'}).click()
 await expect(page.getByRole('button',{name:/Sign in securely/})).toBeVisible()
 await expect(page.getByText('Recorded CI Owner B')).toHaveCount(0)
})
