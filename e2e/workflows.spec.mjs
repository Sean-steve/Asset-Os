import {test,expect} from '@playwright/test'
const KEY='asset-os:registry:v1'
const state=page=>page.evaluate(key=>JSON.parse(localStorage.getItem(key)),KEY)

test('asset → acquisition → portfolio → maintenance → reminders persists through reload',async({page})=>{
  const exceptions=[]
  page.on('pageerror',e=>exceptions.push(e.message))
  await page.goto('./#/assets/new')
  await page.getByRole('textbox',{name:/Asset name/i}).fill('Certification vehicle fixture')
  await page.getByRole('spinbutton',{name:/Preview asset value/i}).fill('1500')
  await page.getByRole('spinbutton',{name:/Preview equity/i}).fill('1500')
  await page.getByRole('button',{name:'Create asset',exact:true}).click()
  const saved=await state(page)
  const asset=saved.records.find(a=>a.name==='Certification vehicle fixture')
  expect(asset).toBeTruthy()
  expect(asset.origin).toBe('local')
  expect(saved.version).toBe(6)
  await expect(page).toHaveURL(new RegExp('#/asset/'+asset.id+'$'))
  await page.reload()
  expect((await state(page)).records.some(a=>a.id===asset.id)).toBeTruthy()

  await page.goto('./#/acquisitions/new?asset='+encodeURIComponent(asset.id))
  await page.getByRole('button',{name:/Begin acquisition/i}).click()
  await page.getByRole('spinbutton',{name:/Purchase \/ consideration/i}).fill('900')
  await page.getByRole('textbox',{name:/Counterparty \(non-sensitive label\)/i}).fill('Certification supplier')
  await page.getByRole('button',{name:'Record acquisition',exact:true}).click()
  await expect.poll(async()=> (await state(page)).phase2.acquisitions.filter(a=>a.assetId===asset.id).length).toBe(1)
  expect((await state(page)).records.find(a=>a.id===asset.id).lifecycle).toBe('ACQUIRED')

  await page.goto('./#/portfolios')
  await page.getByRole('button',{name:'Create portfolio',exact:true}).click()
  await page.getByRole('textbox',{name:/Portfolio name/i}).fill('Certified portfolio')
  await page.getByRole('button',{name:'Create portfolio',exact:true}).click()
  await expect.poll(async()=> (await state(page)).phase5.portfolios.length).toBe(1)
  await page.getByRole('button',{name:'Open portfolio Certified portfolio'}).click()
  await page.getByLabel('Available assets').selectOption(asset.id)
  await page.getByRole('button',{name:'Add',exact:true}).click()
  await expect.poll(async()=> (await state(page)).phase5.memberships.filter(m=>m.assetId===asset.id&&!m.removedAt).length).toBe(1)

  await page.goto('./#/maintenance/plans')
  await page.getByRole('button',{name:/Create plan/i}).click()
  await page.getByLabel('Asset',{exact:true}).selectOption(asset.id)
  await page.getByRole('textbox',{name:/Maintenance task/i}).fill('Certification inspection')
  await page.getByRole('button',{name:'Save maintenance plan'}).click()
  await expect.poll(async()=> (await state(page)).phase4.plans.filter(p=>p.assetId===asset.id).length).toBe(1)

  await page.goto('./#/notifications')
  await expect(page.getByText('Certification inspection').first()).toBeVisible()
  await page.reload()
  const after=await state(page)
  expect(after.phase2.acquisitions.some(a=>a.assetId===asset.id)).toBe(true)
  expect(after.phase4.plans.some(p=>p.assetId===asset.id)).toBe(true)
  expect(after.phase5.memberships.some(p=>p.assetId===asset.id&&!p.removedAt)).toBe(true)
  expect(exceptions).toEqual([])
})

test('settings remain local, change reminder horizon, and do not grant a real role',async({page})=>{
  await page.goto('./#/settings')
  await page.getByLabel('Preview reminder horizon').selectOption('7')
  await page.getByLabel('Role display preference').selectOption('VIEWER')
  await page.getByRole('button',{name:'Save preview settings'}).click()
  await expect.poll(async()=> (await state(page)).phase6.settings.reminderHorizonDays).toBe(7)
  await page.reload()
  const saved=await state(page)
  expect(saved.phase6.settings.previewRole).toBe('VIEWER')
  expect(saved.phase6.settings.reminderHorizonDays).toBe(7)
  expect(saved.phase6.teamMembers).toBeUndefined()
  expect(saved.phase6.permissions).toBeUndefined()
  await page.goto('./#/team-access')
  await expect(page.getByText('NO ACCESS ENFORCEMENT')).toBeVisible()
})

test('reports create a local downloadable CSV without a server call',async({page})=>{
  await page.goto('./#/reports')
  const downloadPromise=page.waitForEvent('download')
  await page.getByRole('button',{name:'Export filtered CSV'}).click()
  const download=await downloadPromise
  expect(download.suggestedFilename()).toMatch(/^asset-registry-KES-\d{4}-\d{2}-\d{2}\.csv$/)
  await expect(page.getByText(/CSV generated in this browser/i)).toBeVisible()
})

test('integration planning never changes disconnected system status',async({page})=>{
  await page.goto('./#/integrations/WEALTH_OS')
  await expect(page.getByText('NOT CONNECTED').first()).toBeVisible()
  await page.getByRole('textbox',{name:/Why should this integration be built/i}).fill('Review an eventual secured read-only projection')
  await page.getByRole('button',{name:'Save local planning note'}).click()
  await expect(page.getByText(/nothing was transmitted/i)).toBeVisible()
  const saved=await state(page)
  expect(saved.phase6.integrationRequests).toHaveLength(1)
  expect(saved.phase6.integrationRequests[0].system).toBe('WEALTH_OS')
  expect(saved.phase6.credentials).toBeUndefined()
  await page.reload()
  await expect(page.getByText('NOT CONNECTED').first()).toBeVisible()
})
