import {test,expect} from '@playwright/test'

const state=page=>page.evaluate(()=>JSON.parse(localStorage.getItem('asset-os:registry:v1')))
const vehicle='sample-vehicle'

test('operations: maintenance plan → service job → completion advances schedule without payment',async({page})=>{
  test.setTimeout(90000)
  await page.goto('./#/maintenance/plans')
  await page.getByRole('button',{name:/Create plan/i}).click()
  await page.getByLabel('Asset',{exact:true}).selectOption(vehicle)
  await page.getByRole('textbox',{name:'Maintenance task'}).fill('Browser-certified vehicle service')
  await page.getByRole('button',{name:'Save maintenance plan'}).click()
  let saved=await state(page)
  const plan=saved.phase4.plans.find(p=>p.assetId===vehicle)
  expect(plan).toBeTruthy()
  expect(plan.status).toBe('ACTIVE')

  await page.goto('./#/maintenance/jobs?plan='+plan.id)
  await page.getByRole('button',{name:'Schedule job'}).click()
  saved=await state(page)
  const job=saved.phase4.jobs.find(j=>j.planId===plan.id)
  expect(job).toBeTruthy()
  expect(job.status).toBe('SCHEDULED')

  await page.getByRole('button',{name:'Start',exact:true}).click()
  await expect.poll(async()=> (await state(page)).phase4.jobs.find(j=>j.id===job.id).status).toBe('IN_PROGRESS')
  await page.getByRole('button',{name:'Complete',exact:true}).click()
  await page.getByRole('spinbutton',{name:/Recorded service cost/i}).fill('125')
  await page.getByRole('button',{name:'Record completion'}).click()
  saved=await state(page)
  expect(saved.phase4.jobs.find(j=>j.id===job.id).status).toBe('COMPLETED')
  expect(saved.phase4.jobs.find(j=>j.id===job.id).recordedCost).toBe(125)
  expect(saved.phase4.plans.find(p=>p.id===plan.id).nextDue).not.toBe(plan.nextDue)
  expect(saved.phase3.flows).toHaveLength(0)
})

test('operations, protection and intelligence store only local evidence and declared observations',async({page})=>{
  test.setTimeout(90000)
  await page.goto('./#/insurance/new')
  await page.getByLabel('Asset',{exact:true}).selectOption(vehicle)
  await page.getByRole('textbox',{name:'Insurer label'}).fill('Certification insurer')
  await page.getByRole('textbox',{name:/Policy reference/i}).fill('SAMPLE-INS-2026')
  const expiry=new Date(Date.now()+365*86400000).toISOString().slice(0,10)
  await page.getByLabel('Coverage expires').fill(expiry)
  await page.getByRole('spinbutton',{name:/Coverage amount/i}).fill('5000')
  await page.getByRole('button',{name:'Save policy reference'}).click()
  expect((await state(page)).phase4.policies.some(p=>p.assetId===vehicle)).toBe(true)

  await page.goto('./#/utilization')
  await page.getByRole('button',{name:'Record reading'}).click()
  await page.getByLabel('Asset',{exact:true}).selectOption(vehicle)
  await page.getByRole('spinbutton',{name:'Cumulative reading'}).fill('2500')
  await page.getByRole('textbox',{name:'Reading source'}).fill('Certification manual meter')
  await page.getByRole('button',{name:'Record observation'}).click()
  expect((await state(page)).phase4.readings.find(r=>r.assetId===vehicle).value).toBe(2500)

  await page.goto('./#/evidence')
  await page.getByRole('button',{name:'Reference evidence'}).click()
  await page.getByLabel('Asset',{exact:true}).selectOption(vehicle)
  await page.getByRole('textbox',{name:'Title'}).fill('Cert fixture inspection')
  await page.getByRole('textbox',{name:'Non-sensitive reference only'}).fill('SAMPLE-CERT-2026')
  await page.getByRole('button',{name:'Save metadata'}).click()
  expect((await state(page)).phase4.documents.some(d=>d.assetId===vehicle)).toBe(true)

  await page.goto('./#/locations')
  await page.getByLabel('Asset',{exact:true}).selectOption(vehicle)
  await page.getByRole('textbox',{name:'Destination label'}).fill('Certification workshop')
  await page.getByRole('button',{name:'Save move'}).click()
  let saved=await state(page)
  expect(saved.records.find(a=>a.id===vehicle).location).toBe('Certification workshop')
  expect(saved.phase4.locations.some(l=>l.assetId===vehicle)).toBe(true)

  await page.goto('./#/risk/new')
  await page.getByLabel('Asset',{exact:true}).selectOption(vehicle)
  await page.getByRole('textbox',{name:/Source \/ assessor label/i}).fill('Owner self review')
  await page.getByRole('textbox',{name:'Explain the observed risks'}).fill('Self reported, not independently verified.')
  await page.getByRole('button',{name:'Record assessment'}).click()
  expect((await state(page)).phase5.risks.some(r=>r.assetId===vehicle)).toBe(true)

  await page.goto('./#/scenarios')
  await page.getByRole('button',{name:'Save scenario inputs'}).click()
  saved=await state(page)
  expect(saved.phase5.scenarios).toHaveLength(1)
  expect(saved.phase6.integrationRequests).toHaveLength(0)
  expect(saved.phase3.flows).toHaveLength(0)
  await page.reload()
  expect((await state(page)).phase5.scenarios).toHaveLength(1)
})
