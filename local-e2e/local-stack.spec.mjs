import {test,expect} from '@playwright/test'
import {randomUUID} from 'node:crypto'
import {readFileSync} from 'node:fs'
test('B4.2-B4.4 real local OIDC + PostgreSQL authenticated asset lifecycle, operations, economics and persistence',async({page})=>{
 const password=process.env.ASSET_OS_E2E_PASSWORD
 if(!password)throw Error('ASSET_OS_E2E_PASSWORD is required for live local certification.')
 const tenant=readFileSync('.local/tenant-id','utf8').trim()
 const name='B4 local E2E '+randomUUID().slice(0,10)
 await page.goto('./#/server-registry')
 await expect(page.getByRole('button',{name:/Sign in securely/})).toBeVisible()
 await page.getByRole('button',{name:/Sign in securely/}).click()
 await expect(page).toHaveURL(/127\.0\.0\.1:3003\/authorize/)
 await page.getByRole('textbox',{name:'Username'}).fill('owner')
 await page.getByLabel('Password').fill(password)
 await page.getByRole('button',{name:'Sign in securely'}).click()
 await expect(page.getByRole('textbox',{name:'Tenant UUID'})).toHaveValue(tenant)
 await page.getByRole('button',{name:'Verify membership'}).click()
 await expect(page.getByText('Verified tenant').first()).toBeVisible()
 await page.getByRole('button',{name:'Register asset',exact:true}).click()
 await page.getByRole('textbox',{name:'Asset name'}).fill(name)
 await page.getByRole('textbox',{name:'Location label'}).fill('Nairobi')
 await page.getByRole('textbox',{name:'Registry value (KES, decimal string)'}).fill('100000.00')
 await page.getByLabel('Value effective date').fill('2026-11-01')
 await page.getByRole('button',{name:'Register asset',exact:true}).click()
 await expect(page.getByRole('heading',{name})).toBeVisible()
 const path=new URL(page.url()).hash
 const assetId=path.match(/asset\/([0-9a-f-]{36})/)?.[1]
 expect(assetId).toBeTruthy()
 await page.getByRole('button',{name:/Acquisition, lifecycle & ownership/}).click()
 await page.getByRole('textbox',{name:'Lifecycle reason'}).fill('Local OIDC PostgreSQL E2E')
 await page.getByRole('button',{name:'Begin acquisition'}).click()
 await expect(page.getByRole('button',{name:'Record acquisition'})).toBeVisible()
 await page.getByRole('textbox',{name:'Acquisition purchase'}).fill('1000.00')
 await page.getByRole('button',{name:'Record acquisition'}).click()
 await expect(page.getByText(/Recorded cost basis:/)).toBeVisible()
 await page.getByRole('textbox',{name:'Lifecycle reason'}).fill('Put asset into operations')
 await page.getByRole('button',{name:'Activate'}).click()
 await expect(page.getByText('ACTIVE').first()).toBeVisible()
 await page.getByRole('button',{name:/Registry details/}).click()
 await page.getByRole('button',{name:/Maintenance, insurance & operations/}).click()
 await expect(page.getByRole('heading',{name})).toBeVisible()
 await page.getByRole('tab',{name:'Maintenance'}).click()
 await page.getByRole('textbox',{name:'Plan title'}).fill('Real PostgreSQL local plan')
 await page.getByLabel('Interval (1–365)').fill('2')
 await page.getByLabel('Cycle unit').selectOption('MONTHS')
 await page.getByLabel('Next due date').fill('2026-12-01')
 await page.getByRole('button',{name:'Record maintenance plan'}).click()
 await expect(page.getByText('Real PostgreSQL local plan').first()).toBeVisible()
 // Same server records, new workspace navigation with no browser-local fallback.
 await page.evaluate(()=>{window.location.hash='/server-registry/workspace'})
 await expect(page.getByRole('heading',{name:'Connected Asset Workspace'})).toBeVisible()
 await expect(page.getByText(name).first()).toBeVisible()
 await page.getByRole('button',{name:'Economics'}).first().click()
 await expect(page.getByText(name).first()).toBeVisible()
 await page.evaluate(id=>{window.location.hash='/server-registry/asset/'+id+'/operations'},assetId)
 await page.getByRole('tab',{name:'Maintenance'}).click()
 await expect(page.getByText('Real PostgreSQL local plan').first()).toBeVisible()
 const storage=await page.evaluate(()=>JSON.stringify(localStorage)+JSON.stringify(sessionStorage))
 expect(storage).not.toContain('Real PostgreSQL local plan')
 expect(storage).not.toContain('eyJ')
})
